#!/usr/bin/env python3
"""Generate the Swift package under gen/swift/ for the tracker schemas.

Scope is deliberate: ONLY ``schemas/tracker/{hello,frame-status,frame-needle}.json``
plus the one constant that wire speaks (TRACKER_SUPPORTED_PROTOCOL_VERSIONS). The
consumer is the native iPad app, a tracker client; it has no business with the
device NDJSON, the angle stream or the plan channel, and generating types for
them would only create surface to keep in step.

Like every generator here the output is committed and diffed by CI, so it is a
pure function of its inputs -- no timestamps, no host paths, no unordered
iteration. Standard library only, so no new dependency enters the toolchain.

Decisions worth knowing before reading the output:

* **Strict where the schema is strict.** A property in ``required`` must be
  present; ``["number", "null"]`` required fields are ``Double?`` but still must
  appear, because ``frame-needle.json`` rejects a v1 rig by their absence. Swift's
  synthesized ``Decodable`` would quietly accept the absence of any Optional, so
  ``init(from:)`` is generated rather than synthesized.
* **Open objects.** ``additionalProperties: true`` is Codable's default: keys not
  in ``CodingKeys`` are ignored. The generator refuses any other value instead of
  silently ignoring it.
* **Closed enums, ``const`` checked.** An unknown enum value is a decode error
  (the schemas' own samples reject it). A ``const`` property is not stored; it is
  verified on decode, written on encode, and exposed as a static.
* **Nested objects** (``hello.phantom``) become nested structs named after their owner and
  property (``TrackerHelloPhantom``); they must say ``additionalProperties: true`` for the
  same reason as the top level.
* **Unsupported schema keywords fail generation** rather than being dropped, so
  a schema edit that this generator cannot express is a red build, not a
  contract the Swift types quietly do not enforce.
"""

from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "gen" / "swift"
SOURCES = OUT / "Sources" / "NeedleProtocol"
TESTS = OUT / "Tests" / "NeedleProtocolTests"

# Order is the order of the generated file; it is also the whole scope.
SCHEMAS = [
    "schemas/tracker/hello.json",
    "schemas/tracker/frame-status.json",
    "schemas/tracker/frame-needle.json",
]
CONSTANTS = ["TRACKER_SUPPORTED_PROTOCOL_VERSIONS"]

# The hand-written Swift test lives with the other suites and is copied verbatim
# (like angles/py in gen-py.py), so that the package carries its own tests while
# gen/ stays 100% machine-written.
TEST_SOURCE = ROOT / "tests" / "swift" / "SamplesTests.swift"

BANNER = """\
// AUTO-GENERATED BY tools/gen.sh. DO NOT EDIT.
//
// Source: {source}
// Regenerate with `tools/gen.sh`; CI fails on any drift.
"""

PROPERTY_KEYS = {
    "type", "description", "enum", "const", "minimum", "exclusiveMinimum", "minLength", "items",
    "properties", "required", "additionalProperties",
}
SCHEMA_KEYS = {
    "$id", "$schema", "title", "description", "x-version", "type", "$comment",
    "additionalProperties", "properties", "required",
}

SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func",
    "import", "init", "inout", "internal", "let", "open", "operator", "private",
    "precedencegroup", "protocol", "public", "rethrows", "static", "struct",
    "subscript", "typealias", "var", "break", "case", "catch", "continue", "default",
    "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat",
    "return", "throw", "switch", "where", "while", "as", "false", "is", "nil",
    "self", "super", "throws", "true", "try", "Any", "Self", "Type", "Protocol",
}


class GenerationError(Exception):
    pass


def pascal(slug: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[-_]", slug))


def camel(name: str) -> str:
    """`skin_entry_x` -> `skinEntryX`; an already-camelCase `tipX` is unchanged."""
    parts = re.split(r"[-_]", name)
    out = parts[0][:1].lower() + parts[0][1:] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return out


def ident(name: str) -> str:
    return f"`{name}`" if name in SWIFT_KEYWORDS else name


def wrap(text: str, width: int) -> list[str]:
    lines: list[str] = []
    line = ""
    for word in text.split():
        if not line:
            line = word
        elif len(line) + 1 + len(word) <= width:
            line += f" {word}"
        else:
            lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines


def doc(text: str, indent: str = "") -> list[str]:
    return [f"{indent}/// {line}" for line in wrap(text, 96)]


def swift_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def slug_of(path: str) -> str:
    # schemas/tracker/frame-needle.json -> tracker-frame-needle, as bundle.mjs does.
    return path.removeprefix("schemas/").removesuffix(".json").replace("/", "-")


class Field:
    def __init__(self, wire: str, spec: dict, required: bool, owner: str, where: str):
        unknown = set(spec) - PROPERTY_KEYS
        if unknown:
            raise GenerationError(f"{where}.{wire}: unsupported schema keyword(s) {sorted(unknown)}")
        self.wire = wire
        self.name = ident(camel(wire))
        self.bare = camel(wire)
        self.description = spec.get("description", "")
        self.required = required
        self.const = spec.get("const")
        self.minimum = spec.get("minimum")
        self.exclusive_minimum = spec.get("exclusiveMinimum")
        self.min_length = spec.get("minLength")
        self.nested_schema: dict | None = None
        self.nested_type: str | None = None
        self.enum_type: str | None = None
        self.enum_values: list[str] = []

        types = spec["type"] if "type" in spec else None
        if self.const is not None:
            if not isinstance(self.const, str):
                raise GenerationError(f"{where}.{wire}: only string const is supported")
            self.swift = "String"
            self.nullable = False
            return
        if types is None:
            raise GenerationError(f"{where}.{wire}: no type")
        kinds = types if isinstance(types, list) else [types]
        self.nullable = "null" in kinds
        kinds = [k for k in kinds if k != "null"]
        if len(kinds) != 1:
            raise GenerationError(f"{where}.{wire}: unsupported type {types!r}")
        kind = kinds[0]
        if kind == "array":
            item = spec.get("items")
            if not item or item.get("type") != "string" or "enum" not in item:
                raise GenerationError(f"{where}.{wire}: only arrays of string enums are supported")
            self.enum_type = owner + camel_pascal(wire)
            self.enum_values = item["enum"]
            self.swift = f"[{self.enum_type}]"
        elif kind == "object":
            if spec.get("additionalProperties") is not True or "properties" not in spec:
                raise GenerationError(
                    f"{where}.{wire}: a nested object needs `properties` and "
                    "`additionalProperties: true`"
                )
            self.nested_schema = spec
            self.nested_type = owner + camel_pascal(wire)
            self.swift = self.nested_type
        elif kind == "string" and "enum" in spec:
            self.enum_type = owner + camel_pascal(wire)
            self.enum_values = spec["enum"]
            self.swift = self.enum_type
        else:
            try:
                self.swift = {"integer": "Int", "number": "Double", "string": "String", "boolean": "Bool"}[kind]
            except KeyError:
                raise GenerationError(f"{where}.{wire}: unsupported type {kind!r}") from None
        if self.minimum is not None and kind != "integer":
            raise GenerationError(f"{where}.{wire}: minimum is only supported on integers")
        if self.exclusive_minimum is not None and kind != "number":
            raise GenerationError(f"{where}.{wire}: exclusiveMinimum is only supported on numbers")
        if self.min_length is not None and kind != "string":
            raise GenerationError(f"{where}.{wire}: minLength is only supported on strings")

    @property
    def optional(self) -> bool:
        return self.nullable or not self.required

    @property
    def swift_type(self) -> str:
        return self.swift + ("?" if self.optional else "")


def camel_pascal(wire: str) -> str:
    c = camel(wire)
    return c[:1].upper() + c[1:]


def render_enum(field: Field) -> list[str]:
    lines = [f"/// Values of `{field.wire}` on the wire, in schema order."]
    lines.append(f"public enum {field.enum_type}: String, Codable, Sendable, Equatable, CaseIterable {{")
    seen: set[str] = set()
    for value in field.enum_values:
        case = camel(value)
        if case in seen:
            raise GenerationError(f"{field.wire}: enum values collide on Swift case `{case}`")
        seen.add(case)
        if case == value:
            lines.append(f"    case {ident(case)}")
        else:
            lines.append(f"    case {ident(case)} = {swift_string(value)}")
    lines.append("}")
    return lines


def render_struct(path: str) -> list[str]:
    schema = json.loads((ROOT / path).read_text(encoding="utf-8"))
    where = path
    unknown = set(schema) - SCHEMA_KEYS
    if unknown:
        raise GenerationError(f"{where}: unsupported schema keyword(s) {sorted(unknown)}")
    if schema.get("type") != "object":
        raise GenerationError(f"{where}: top level must be an object")
    if schema.get("additionalProperties") is not True:
        raise GenerationError(
            f"{where}: additionalProperties must be true; Codable ignores unknown keys and this "
            "generator cannot express a closed object"
        )
    header = doc(schema["description"]) + [
        f"/// Schema `x-version` {schema['x-version']}; source `{path}`."
    ]
    return render_object(schema, pascal(slug_of(path)), where, header)


def render_object(schema: dict, name: str, where: str, header: list[str]) -> list[str]:
    required = set(schema.get("required", []))
    fields = [
        Field(wire, spec, wire in required, name, where)
        for wire, spec in schema["properties"].items()
    ]
    missing = required - {f.wire for f in fields}
    if missing:
        raise GenerationError(f"{where}: required names with no property: {sorted(missing)}")
    consts = [f for f in fields if f.const is not None]
    stored = [f for f in fields if f.const is None]

    out: list[str] = []
    for f in stored:
        if f.enum_type:
            out += render_enum(f) + [""]
        if f.nested_schema is not None:
            out += render_object(
                f.nested_schema, f.nested_type, f"{where}.{f.wire}", doc(f.description)
            ) + [""]

    out += header
    out += [f"public struct {name}: Codable, Sendable, Equatable {{"]
    for f in consts:
        out += doc(f.description or f"Always `{f.const}`; checked on decode.", "    ")
        out += [f"    public static let {f.bare} = {swift_string(f.const)}", ""]
    for f in stored:
        out += doc(f.description, "    ")
        out += [f"    public var {f.name}: {f.swift_type}", ""]

    # Memberwise initialiser: a struct with `public` members has only an
    # internal one, and consumers (and their tests) need to build frames.
    params = ",\n".join(
        f"        {f.name}: {f.swift_type}" + (" = nil" if f.optional and not f.required else "")
        for f in stored
    )
    out += ["    public init("]
    out += [params, "    ) {"]
    out += [f"        self.{f.name} = {f.name}" for f in stored]
    out += ["    }", ""]

    out += ["    private enum CodingKeys: String, CodingKey {"]
    for f in fields:
        if f.bare == f.wire:
            out += [f"        case {f.name}"]
        else:
            out += [f"        case {f.name} = {swift_string(f.wire)}"]
    out += ["    }", ""]

    out += ["    public init(from decoder: Decoder) throws {"]
    out += ["        let container = try decoder.container(keyedBy: CodingKeys.self)"]
    for f in consts:
        out += [
            f"        let {f.bare}Value = try container.decode(String.self, forKey: .{f.name})",
            f"        guard {f.bare}Value == Self.{f.bare} else {{",
            "            throw DecodingError.dataCorruptedError(",
            f"                forKey: .{f.name}, in: container,",
            f"                debugDescription: \"expected {f.wire} == \\(Self.{f.bare}.debugDescription), got \\({f.bare}Value.debugDescription)\")",
            "        }",
        ]
    for f in stored:
        if f.required and f.nullable:
            # decode, not decodeIfPresent: the key must be present, null allowed.
            out += [f"        self.{f.name} = try container.decode({f.swift}?.self, forKey: .{f.name})"]
        elif f.required:
            out += [f"        self.{f.name} = try container.decode({f.swift}.self, forKey: .{f.name})"]
        else:
            out += [f"        self.{f.name} = try container.decodeIfPresent({f.swift}.self, forKey: .{f.name})"]
        if f.exclusive_minimum is not None:
            check = (
                f"if let value = self.{f.name}, value <= {f.exclusive_minimum}"
                if f.optional
                else f"if self.{f.name} <= {f.exclusive_minimum}"
            )
            out += [
                f"        {check} {{",
                "            throw DecodingError.dataCorruptedError(",
                f"                forKey: .{f.name}, in: container,",
                f"                debugDescription: \"{f.wire} must be > {f.exclusive_minimum}\")",
                "        }",
            ]
        if f.min_length is not None:
            check = (
                f"if let value = self.{f.name}, value.count < {f.min_length}"
                if f.optional
                else f"if self.{f.name}.count < {f.min_length}"
            )
            out += [
                f"        {check} {{",
                "            throw DecodingError.dataCorruptedError(",
                f"                forKey: .{f.name}, in: container,",
                f"                debugDescription: \"{f.wire} must have at least {f.min_length} character(s)\")",
                "        }",
            ]
        if f.minimum is not None:
            check = (
                f"if let value = self.{f.name}, value < {f.minimum}"
                if f.optional
                else f"if self.{f.name} < {f.minimum}"
            )
            out += [
                f"        {check} {{",
                "            throw DecodingError.dataCorruptedError(",
                f"                forKey: .{f.name}, in: container,",
                f"                debugDescription: \"{f.wire} must be >= {f.minimum}\")",
                "        }",
            ]
    out += ["    }", ""]

    out += ["    public func encode(to encoder: Encoder) throws {"]
    out += ["        var container = encoder.container(keyedBy: CodingKeys.self)"]
    for f in consts:
        out += [f"        try container.encode(Self.{f.bare}, forKey: .{f.name})"]
    for f in stored:
        if f.required:
            # An Optional encodes as an explicit null, which is what the wire carries.
            out += [f"        try container.encode(self.{f.name}, forKey: .{f.name})"]
        else:
            out += [f"        try container.encodeIfPresent(self.{f.name}, forKey: .{f.name})"]
    out += ["    }", "}"]
    return out


def swift_array_literal(values: list[int]) -> str:
    return "[" + ", ".join(str(v) for v in values) + "]"


def render_constants(constants: dict) -> str:
    lines = [BANNER.format(source="constants/constants.json"), "public enum NeedleProtocolConstants {"]
    for key in CONSTANTS:
        spec = constants["constants"][key]
        if spec["type"] != "integer[]":
            raise GenerationError(f"{key}: only integer[] constants are supported here")
        lines += doc(spec["description"], "    ")
        if spec.get("sources"):
            lines += ["    ///", "    /// Mirrors:"]
            lines += [f"    /// - {s}" for s in spec["sources"]]
        lines += [
            f"    public static let {camel(key.lower())}: [Int] = {swift_array_literal(spec['value'])}",
        ]
    lines += ["}"]
    return "\n".join(lines) + "\n"


PACKAGE_SWIFT = """\
// swift-tools-version: 5.9
// AUTO-GENERATED BY tools/gen.sh. DO NOT EDIT.
//
// Source: tools/gen-swift.py
// Regenerate with `tools/gen.sh`; CI fails on any drift.

import PackageDescription

let package = Package(
    name: "NeedleProtocol",
    platforms: [.iOS(.v16), .macOS(.v13)],
    products: [
        .library(name: "NeedleProtocol", targets: ["NeedleProtocol"]),
    ],
    targets: [
        .target(name: "NeedleProtocol"),
        .testTarget(name: "NeedleProtocolTests", dependencies: ["NeedleProtocol"]),
    ]
)
"""


def main() -> int:
    constants = json.loads((ROOT / "constants" / "constants.json").read_text(encoding="utf-8"))

    # Wipe first: a schema that leaves the list must take its generated file
    # with it, and stale output under gen/ is exactly what CI is meant to see.
    # Only the directories this writes: a developer's `swift build` leaves .build/
    # beside them, and deleting that would turn every regeneration into a rebuild.
    shutil.rmtree(OUT / "Sources", ignore_errors=True)
    shutil.rmtree(OUT / "Tests", ignore_errors=True)
    SOURCES.mkdir(parents=True)
    TESTS.mkdir(parents=True)

    try:
        for path in SCHEMAS:
            body = render_struct(path)
            name = pascal(slug_of(path))
            (SOURCES / f"{name}.swift").write_text(
                BANNER.format(source=path) + "\nimport Foundation\n\n" + "\n".join(body) + "\n",
                encoding="utf-8",
            )
        (SOURCES / "Constants.swift").write_text(render_constants(constants), encoding="utf-8")
    except GenerationError as err:
        print(f"[gen-swift] {err}", file=sys.stderr)
        return 1

    (OUT / "Package.swift").write_text(PACKAGE_SWIFT, encoding="utf-8")
    (TESTS / TEST_SOURCE.name).write_text(
        BANNER.format(source="tests/swift/SamplesTests.swift (copied verbatim)")
        + "\n"
        + TEST_SOURCE.read_text(encoding="utf-8"),
        encoding="utf-8",
    )
    print(f"[gen-swift] gen/swift from {len(SCHEMAS)} schema(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
